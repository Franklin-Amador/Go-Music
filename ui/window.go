type mainUI struct {
	win        fyne.Window
	cfg        *appConfig
	root       fyne.CanvasObject
	titleText  *canvas.Text
	artistText *canvas.Text
	albumText  *canvas.Text
	formatText *canvas.Text
	posLabel   *canvas.Text
	durLabel   *canvas.Text
	modeLabel  *canvas.Text
	progress   *widget.Slider
	playBtn    *widget.Button
	listWidget *widget.List
	artBg       *canvas.Rectangle
	artImage    *canvas.Image
	artGlyph    *canvas.Text
	bgGradient  *canvas.LinearGradient // album-derived ambient backdrop for the right column
	currentAccent color.NRGBA          // dominant color of the current track (zero when not set)
	eng         *audio.Engine
	pl          *playlist.Playlist
	seeking     bool
	updatingUI  bool
	// suppressSelect guards programmatic listWidget.Select() calls from
	// triggering OnSelected — which would re-enter loadAndPlay and loop.
	suppressSelect bool
	shuffleBtn  *widget.Button
	shuffleDot  *canvas.Circle
	repeatTrack bool // when true, OnFinished restarts the same track instead of advancing
	repeatBtn   *widget.Button
	repeatDot   *canvas.Circle

	// Lyrics panel state
	mainSplit      *container.Split // root horizontal split (playlist | rest)
	rightContainer *fyne.Container  // holds player + optional lyrics panel
	playerColumn   fyne.CanvasObject
	lyricsPanel    fyne.CanvasObject
	lyricsBox      *fyne.Container // VBox of canvas.Text lines
	lyricsScroll   *container.Scroll
	lyricsHeader   *canvas.Text
	lyricsLines    []audio.LyricLine
	currentLyric   int
	showLyrics     bool
	lyricsToken    int              // increments per Load — async fetches check before applying
	lineAnims      []*fyne.Animation // in-flight color/size animations on lyric lines
	scrollAnim     *fyne.Animation   // in-flight smooth-scroll animation

	// Waveform visualizer
	wave *waveformWidget

	// Playlist search/filter
	//
	// `filtered` is the index map applied between the visible list and the
	// underlying pl.Tracks slice. When non-nil it overrides Length/UpdateItem
	// so the list only shows matching rows; nil means "no filter, show all".
	// Selection on a filtered row maps back to the real index before calling
	// pl.SetCurrent, so reordering and Current tracking still operate on the
	// canonical playlist.
	searchEntry *widget.Entry
	searchBar   fyne.CanvasObject
	filtered    []int

	// ── Library view ────────────────────────────────────────────────────
	// lib is the loaded music index; nil until the user picks a music
	// root or a cached library file is loaded on startup. albumGrid and
	// artistList are the two browsing widgets, displayed inside libTabs
	// next to the Playlist tab. artistFilter narrows the album grid down
	// to a single artist when the user clicks one in the Artists tab; an
	// empty string shows every album.
	lib            *library.Library
	libTabs        *container.AppTabs
	albumList      *widget.List
	artistList     *widget.List
	songList       *widget.List    // flat all-tracks list in Songs tab
	allTracks      []*library.Track // source slice for songList
	libStatus      *canvas.Text     // text shown on Albums tab when empty / scanning
	libClearFilter *widget.Button   // "× clear" — visible only when artistFilter != ""
	artistFilter   string           // album-grid scope: "" = all, otherwise that artist name
	visibleAlbums  []*library.Album // recomputed when filter changes
	coverCache     map[*library.Album]fyne.Resource
}

// ── Layout ───────────────────────────────────────────────────────────────────

func buildUI(w fyne.Window, eng *audio.Engine, pl *playlist.Playlist, cfg *appConfig) *mainUI {
	ui := &mainUI{eng: eng, pl: pl, win: w, cfg: cfg, showLyrics: cfg.ShowLyrics}

	// ── Album art block ──────────────────────────────────────────────────
	// Min sizes are modest so the art can shrink for small windows (the
	// squareCenterLayout below grows it back up to fill the available
	// space). Lower MinSize → smaller window MinSize → the user can drag
	// the window down to laptop-screen sizes.
	ui.artBg = canvas.NewRectangle(colorBgElevated)
	ui.artBg.SetMinSize(fyne.NewSize(180, 180))
	ui.artBg.CornerRadius = 10

	ui.artGlyph = canvas.NewText("♪", color.NRGBA{R: 0xff, G: 0xff, B: 0xff, A: 0x55})
	ui.artGlyph.TextSize = 110
	ui.artGlyph.Alignment = fyne.TextAlignCenter
	ui.artGlyph.TextStyle = fyne.TextStyle{Bold: true}

	ui.artImage = &canvas.Image{}
	ui.artImage.FillMode = canvas.ImageFillContain
	ui.artImage.SetMinSize(fyne.NewSize(180, 180))
	ui.artImage.Hide()

	artStack := container.NewStack(
		ui.artBg,
		container.NewCenter(ui.artGlyph),
		ui.artImage,
	)

	// ── Track header text (title / artist / album) ───────────────────────
	ui.titleText = canvas.NewText("No track loaded", colorText)
	ui.titleText.TextSize = 28
	ui.titleText.TextStyle = fyne.TextStyle{Bold: true}
	ui.titleText.Alignment = fyne.TextAlignCenter

	ui.artistText = canvas.NewText("", colorText)
	ui.artistText.TextSize = 16
	ui.artistText.Alignment = fyne.TextAlignCenter

	ui.albumText = canvas.NewText("Open a file or folder to begin", colorTextDim)
	ui.albumText.TextSize = 13
	ui.albumText.Alignment = fyne.TextAlignCenter

	ui.formatText = canvas.NewText("", colorAccent)
	ui.formatText.TextSize = 12
	ui.formatText.TextStyle = fyne.TextStyle{Bold: true}
	ui.formatText.Alignment = fyne.TextAlignCenter

	headerBlock := container.NewVBox(
		ui.titleText,
		spacer(2),
		ui.artistText,
		ui.albumText,
		spacer(4),
		ui.formatText,
	)

	// ── Progress ─────────────────────────────────────────────────────────
	// The slider seeks on both drag AND click. OnChanged is called
	// continuously while the user drags, but the engine's Seek for DSD does
	// a full producer restart and Reset's oto's buffer for PCM — both are
	// disruptive if fired on every drag tick. So during a drag we just
	// update the UI labels; the actual eng.Seek runs once when OnChangeEnded
	// fires (drag release / click landed). For PCM that lands instantly; for
	// DSD it triggers the brief stop-restart.
	ui.posLabel = canvas.NewText("0:00", colorTextDim)
	ui.posLabel.TextSize = 11
	ui.durLabel = canvas.NewText("0:00", colorTextDim)
	ui.durLabel.TextSize = 11
	ui.durLabel.Alignment = fyne.TextAlignTrailing
	ui.modeLabel = canvas.NewText("", colorTextDim)
	ui.modeLabel.TextSize = 10
	ui.modeLabel.Alignment = fyne.TextAlignCenter

	ui.progress = widget.NewSlider(0, 1)
	ui.progress.Step = 0.0001
	ui.progress.OnChanged = func(v float64) {
		if ui.updatingUI {
			return
		}
		ui.seeking = true
		if eng.Info != nil {
			ui.posLabel.Text = fmtDuration(v * eng.Info.Duration)
			ui.posLabel.Refresh()
		}
	}
	ui.progress.OnChangeEnded = func(v float64) {
		// CRITICAL: Fyne's Slider.SetValue internally calls fireChangeEnded —
		// so every programmatic position update from OnPositionChange would
		// look like a "user finished a drag" event and trigger eng.Seek to
		// the position we just reported. For PCM that pulls pcmPos backwards
		// by the buffered-frames count (because Position() subtracts oto's
		// BufferedSize), the oto buffer then replays its older samples, and
		// the song appears to loop inside the first second. For DSD it
		// kicks off a full producer restart every 250 ms. The updatingUI
		// guard mirrors the one on OnChanged.
		if ui.updatingUI {
			return
		}
		if eng.Info != nil {
			eng.Seek(v * eng.Info.Duration)
		}
		// Release the lock that prevents the position timer from overwriting
		// the slider, but only after the engine has had a moment to refresh
		// internal counters — otherwise the very next position tick would
		// snap us back to the pre-seek frame.
		go func() {
			time.Sleep(60 * time.Millisecond)
			fyne.Do(func() { ui.seeking = false })
		}()
	}

	timeRow := container.New(layout.NewBorderLayout(nil, nil, ui.posLabel, ui.durLabel),
		ui.posLabel, ui.durLabel,
		container.NewCenter(ui.modeLabel),
	)

	progressBlock := container.NewVBox(
		ui.progress,
		timeRow,
	)

	// ── Transport controls ───────────────────────────────────────────────
	// Layout:  [shuffle]   ⏮  ⏹  ▶  ⏭   [repeat]
	// The play button is larger (HighImportance + container.NewGridWrap to
	// force a bigger min size) so it's the obvious primary target.
	prevBtn := iconButton(theme.MediaSkipPreviousIcon(), ui.goPrev)
	nextBtn := iconButton(theme.MediaSkipNextIcon(), ui.goNext)
	stopBtn := iconButton(theme.MediaStopIcon(), ui.stopPlayback)

	ui.playBtn = widget.NewButtonWithIcon("", theme.MediaPlayIcon(), ui.togglePlay)
	ui.playBtn.Importance = widget.HighImportance
	playSized := container.NewGridWrap(fyne.NewSize(56, 40), ui.playBtn)

	// Shuffle/repeat stay LowImportance (transparent background, white icon)
	// in BOTH active and inactive states — the user explicitly didn't want
	// the accent-green active highlight. State feedback is by the small dot
	// indicator below each button (toggled in refreshShuffleVisual /
	// toggleRepeat).
	ui.shuffleBtn = widget.NewButtonWithIcon("", shuffleIconResource, ui.toggleShuffle)
	ui.shuffleBtn.Importance = widget.LowImportance

	ui.repeatBtn = widget.NewButtonWithIcon("", repeatIconResource, ui.toggleRepeat)
	ui.repeatBtn.Importance = widget.LowImportance

	ui.shuffleDot = canvas.NewCircle(color.Transparent)
	ui.shuffleDot.StrokeWidth = 0
	ui.repeatDot = canvas.NewCircle(color.Transparent)
	ui.repeatDot.StrokeWidth = 0
	ui.refreshShuffleVisual()
	ui.refreshRepeatVisual()

	// Each toggle button is wrapped in a VBox over a tiny "dot" so the active
	// state is visible without changing the icon color.
	shuffleStack := container.NewVBox(
		ui.shuffleBtn,
		container.NewGridWrap(fyne.NewSize(6, 6), ui.shuffleDot),
	)
	repeatStack := container.NewVBox(
		ui.repeatBtn,
		container.NewGridWrap(fyne.NewSize(6, 6), ui.repeatDot),
	)

	transport := container.NewCenter(container.NewHBox(
		shuffleStack,
		spacerH(14),
		prevBtn,
		spacerH(6),
		stopBtn,
		spacerH(6),
		playSized,
		spacerH(6),
		nextBtn,
		spacerH(14),
		repeatStack,
	))

	// ── Volume ───────────────────────────────────────────────────────────
	volSlider := widget.NewSlider(0, 1)
	volSlider.Value = float64(eng.Volume) // restored from config
	volSlider.Step = 0.01
	volSlider.OnChanged = func(v float64) {
		eng.Volume = float32(v)
	}
	volSlider.OnChangeEnded = func(float64) {
		ui.cfg.Volume = eng.Volume
		ui.cfg.save()
	}
	volIcon := widget.NewIcon(theme.VolumeUpIcon())

	lyricsToggle := widget.NewButtonWithIcon("Lyrics", theme.DocumentIcon(), func() {
		ui.toggleLyrics()
	})
	lyricsToggle.Importance = widget.LowImportance

	volRow := container.New(layout.NewBorderLayout(nil, nil, volIcon, lyricsToggle),
		volIcon,
		lyricsToggle,
		volSlider,
	)

	// ── Waveform visualizer ──────────────────────────────────────────────
	ui.wave = newWaveformWidget(96)
	ui.wave.OnSeek = func(frac float64) {
		if eng.Info == nil {
			return
		}
		target := frac * eng.Info.Duration
		eng.Seek(target)
		// Update the progress slider immediately so it doesn't snap back.
		ui.updatingUI = true
		ui.progress.SetValue(frac)
		ui.updatingUI = false
		ui.wave.SetPosition(float32(frac))
	}
	waveBox := container.NewPadded(ui.wave)

	// ── Right column assembly (responsive) ───────────────────────────────
	// Border layout: art in the center grows to fill all vertical space the
	// window gives it; the controls block sticks to the bottom at its
	// natural height. This means making the window taller makes the art
	// bigger, not the controls.
	bottomBlock := container.NewVBox(
		container.NewPadded(headerBlock),
		spacer(6),
		waveBox,
		spacer(4),
		container.NewPadded(progressBlock),
		spacer(4),
		container.NewPadded(transport),
		spacer(2),
		container.NewPadded(volRow),
		spacer(8),
	)

	// Square-fit + center: the art grows to fill the available space while
	// keeping its aspect ratio. NewCenter alone would freeze it at MinSize.
	artArea := container.NewPadded(container.New(squareCenterLayout{}, artStack))

	// Ambient backdrop: a vertical gradient under the player column whose
	// top color is derived from the current track's album art. Starts fully
	// transparent (no album loaded yet) so the base theme background shows
	// through; applyMetadata fills it in once the cover is decoded.
	ui.bgGradient = canvas.NewVerticalGradient(
		color.NRGBA{},      // top — set per-track
		color.NRGBA{},      // bottom — set per-track (transparent fades to base bg)
	)

	rightColumn := container.NewStack(
		ui.bgGradient,
		container.NewBorder(
			spacer(12),  // top
			bottomBlock, // bottom — fixed natural height
			nil, nil,    // left, right
			artArea, // center — expands
		),
	)

	// ── Left column: playlist ────────────────────────────────────────────
	plHeader := canvas.NewText("PLAYLIST", colorTextDim)
	plHeader.TextSize = 11
	plHeader.TextStyle = fyne.TextStyle{Bold: true}

	addBtn := widget.NewButtonWithIcon("", theme.ContentAddIcon(), func() {
		dialog.ShowFolderOpen(func(lu fyne.ListableURI, err error) {
			if err != nil || lu == nil {
				return
			}
			pl.AddDir(lu.Path())
			ui.applyFilter(ui.searchEntry.Text) // re-evaluate any active filter
			if pl.Current < 0 && pl.Len() > 0 {
				pl.SetCurrent(0)
				if t := pl.CurrentTrack(); t != nil {
					ui.loadAndPlay(t.Path)
				}
			}
		}, w)
	})
	addBtn.Importance = widget.LowImportance

	plHeaderBar := container.NewBorder(nil, nil, container.NewPadded(plHeader), addBtn)

	// Search bar — hidden by default; Ctrl+F toggles + focuses it, Esc closes.
	// Filtering is a pure index remap: filtered[] holds canonical indices of
	// rows that match, the list reads through this remap, and selection maps
	// back to the canonical index so pl.SetCurrent operates on the real
	// playlist regardless of filter state.
	ui.searchEntry = widget.NewEntry()
	ui.searchEntry.SetPlaceHolder("Search title…")
	ui.searchEntry.OnChanged = func(q string) {
		ui.applyFilter(q)
	}
	clearSearchBtn := widget.NewButtonWithIcon("", theme.WindowCloseIcon(), func() {
		ui.hideSearchBar()
	})
	clearSearchBtn.Importance = widget.LowImportance
	ui.searchBar = container.NewBorder(nil, nil, nil, clearSearchBtn, ui.searchEntry)
	ui.searchBar.Hide()

	ui.listWidget = widget.NewList(
		func() int {
			if ui.filtered != nil {
				return len(ui.filtered)
			}
			return pl.Len()
		},
		func() fyne.CanvasObject {
			title := canvas.NewText("", colorText)
			title.TextSize = 13
			subtitle := canvas.NewText("", colorTextDim)
			subtitle.TextSize = 10
			return container.NewVBox(title, subtitle)
		},
		func(id widget.ListItemID, obj fyne.CanvasObject) {
			real := ui.rowToReal(id)
			if real < 0 || real >= pl.Len() {
				return
			}
			box := obj.(*fyne.Container)
			title := box.Objects[0].(*canvas.Text)
			subtitle := box.Objects[1].(*canvas.Text)

			t := pl.Tracks[real]
			ext := ""
			if x := filepath.Ext(t.Path); len(x) > 1 {
				ext = "  " + x[1:]
			}
			if real == pl.Current {
				title.Text = "▸  " + t.Title
				title.Color = colorAccent
				title.TextStyle = fyne.TextStyle{Bold: true}
			} else {
				title.Text = "    " + t.Title
				title.Color = colorText
				title.TextStyle = fyne.TextStyle{}
			}
			subtitle.Text = "    " + ext
			title.Refresh()
			subtitle.Refresh()
		},
	)
	ui.listWidget.OnSelected = func(id widget.ListItemID) {
		// Ignore selections triggered programmatically by syncListSelection
		// — they exist only to update the visual hover, NOT to re-load.
		if ui.suppressSelect {
			return
		}
		real := ui.rowToReal(id)
		if real < 0 || real >= pl.Len() {
			return
		}
		pl.SetCurrent(real) // keeps shuffle order consistent
		if t := pl.CurrentTrack(); t != nil {
			ui.loadAndPlay(t.Path)
		}
	}

	playlistPanel := container.NewBorder(
		container.NewVBox(container.NewPadded(plHeaderBar), ui.searchBar),
		nil, nil, nil,
		ui.listWidget,
	)
	// Three-tab sidebar: Playlist (the existing UI), Albums (cover grid),
	// Artists (drill-down list). buildLibraryTabs stores libTabs/albumGrid/
	// artistList on the mainUI so the scan callbacks can refresh later.
	leftColumn := ui.buildLibraryTabs(playlistPanel)

	// Drag-and-drop support
	w.SetOnDropped(func(_ fyne.Position, uris []fyne.URI) {
		added := false
		for _, u := range uris {
			p := u.Path()
			if playlist.IsSupported(p) {
				pl.Add(p)
				added = true
			}
		}
		if added {
			ui.applyFilter(ui.searchEntry.Text)
			if pl.Current < 0 || eng.CurrentState() == audio.StateStopped {
				pl.SetCurrent(pl.Len() - 1)
				if t := pl.CurrentTrack(); t != nil {
					ui.loadAndPlay(t.Path)
				}
			}
		}
	})

	// ── Lyrics panel (collapsed by default) ──────────────────────────────
	ui.lyricsHeader = canvas.NewText("LYRICS", colorTextDim)
	ui.lyricsHeader.TextSize = 11
	ui.lyricsHeader.TextStyle = fyne.TextStyle{Bold: true}

	ui.lyricsBox = container.NewVBox()
	ui.lyricsScroll = container.NewVScroll(container.NewPadded(ui.lyricsBox))

	closeLyricsBtn := widget.NewButtonWithIcon("", theme.WindowCloseIcon(), func() {
		ui.toggleLyrics()
	})
	closeLyricsBtn.Importance = widget.LowImportance

	lyricsHeaderBar := container.NewBorder(nil, nil,
		container.NewPadded(ui.lyricsHeader),
		closeLyricsBtn,
	)
	ui.lyricsPanel = container.NewBorder(
		container.NewPadded(lyricsHeaderBar),
		nil, nil, nil,
		ui.lyricsScroll,
	)
	ui.setEmptyLyrics("Open a track to see lyrics")

	// ── Compose final layout ─────────────────────────────────────────────
	ui.playerColumn = rightColumn
	ui.rightContainer = container.NewStack(rightColumn) // single child by default
	ui.mainSplit = container.NewHSplit(leftColumn, ui.rightContainer)
	ui.mainSplit.Offset = 0.26
	ui.root = ui.mainSplit

	// ── Engine callbacks ─────────────────────────────────────────────────
	eng.OnStateChange = func(s audio.State) {
		fyne.Do(func() {
			switch s {
			case audio.StatePlaying:
				ui.playBtn.SetIcon(theme.MediaPauseIcon())
			case audio.StateLoading:
				ui.formatText.Text = "Loading…"
				ui.formatText.Refresh()
			default:
				ui.playBtn.SetIcon(theme.MediaPlayIcon())
			}
		})
	}

	eng.OnPositionChange = func(pos, dur float64) {
		fyne.Do(func() {
			ui.posLabel.Text = fmtDuration(pos)
			ui.posLabel.Refresh()
			ui.durLabel.Text = fmtDuration(dur)
			ui.durLabel.Refresh()
			if dur > 0 && !ui.seeking {
				frac := float32(pos / dur)
				ui.updatingUI = true
				ui.progress.SetValue(float64(frac))
				ui.updatingUI = false
				ui.wave.SetPosition(frac)
			}
			if ui.showLyrics {
				ui.updateLyricsPosition(pos)
			}
			ui.maybePreloadNext(pos, dur)
			ui.refreshModeLabel(eng)
		})
	}

	// OnTrackTransition fires from inside the audio thread the moment a
	// preloaded next track first becomes audible (crossfade start). The
	// engine has already promoted the new pcmData internally — we just
	// need to align the UI (title / cover / progress / lyrics) and advance
	// the playlist cursor so subsequent Next/Prev are consistent.
	eng.OnTrackTransition = func(info *audio.FileInfo) {
		fyne.Do(func() {
			// Advance the playlist to the new track. PeekNext().Path is
			// what we Preloaded; matching by path lets shuffle ordering
			// stay correct even if the user mutated the list mid-track.
			for i, t := range pl.Tracks {
				if t.Path == info.Path {
					pl.SetCurrent(i)
					break
				}
			}
			ui.applyMetadata(info)
			ui.updatingUI = true
			ui.progress.SetValue(0)
			ui.updatingUI = false
			ui.posLabel.Text = "0:00"
			ui.posLabel.Refresh()
			ui.durLabel.Text = fmtDuration(info.Duration)
			ui.durLabel.Refresh()
			ui.wave.SetPosition(0)
			ui.syncListSelection()
			ui.setEmptyLyrics("Searching for lyrics…")

			// Fetch lyrics for the new track. Token bumped so any pending
			// fetch for the previous track gets dropped on arrival.
			ui.lyricsToken++
			token := ui.lyricsToken
			go func(info *audio.FileInfo, tok int) {
				lines := audio.FetchLyrics(info)
				fyne.Do(func() {
					if tok != ui.lyricsToken {
						return
					}
					ui.setLyrics(lines)
				})
			}(info, token)
		})
	}

	eng.OnError = func(msg string) {
		fyne.Do(func() {
			dialog.ShowError(fmt.Errorf("%s", msg), w)
		})
	}

	eng.OnFinished = func() {
		fyne.Do(func() {
			if ui.repeatTrack {
				if t := pl.CurrentTrack(); t != nil {
					ui.loadAndPlay(t.Path)
				}
				return
			}
			if t := pl.Next(); t != nil {
				ui.syncListSelection()
				ui.loadAndPlay(t.Path)
			}
		})
	}

	return ui
}

// ── Transport helpers ────────────────────────────────────────────────────────

func (ui *mainUI) goNext() {
	if t := ui.pl.Next(); t != nil {
		ui.syncListSelection()
		ui.loadAndPlay(t.Path)
	}
}

func (ui *mainUI) goPrev() {
	// "Prev within track" UX: if we're more than ~3 s into the song, restart
	// the current track instead of jumping to the previous one. Matches
	// every major player's prev-button behaviour and saves a lot of "oops
	// I meant restart" presses.
	if ui.eng.Info != nil && ui.eng.Position() > 3 {
		ui.eng.Seek(0)
		return
	}
	if t := ui.pl.Prev(); t != nil {
		ui.syncListSelection()
		ui.loadAndPlay(t.Path)
	}
}

func (ui *mainUI) stopPlayback() {
	ui.eng.Stop()
	ui.updatingUI = true
	ui.progress.SetValue(0)
	ui.updatingUI = false
	ui.posLabel.Text = "0:00"
	ui.posLabel.Refresh()
	ui.modeLabel.Text = ""
	ui.modeLabel.Refresh()
	ui.applyAccent(color.NRGBA{}) // restore default green / clear backdrop
	ui.wave.SetPosition(-1)       // hide cursor
}

func (ui *mainUI) seekRelative(deltaSec float64) {
	if ui.eng.Info == nil {
		return
	}
	target := ui.eng.Position() + deltaSec
	if target < 0 {
		target = 0
	}
	if target > ui.eng.Info.Duration {
		target = ui.eng.Info.Duration - 0.1
	}
	ui.eng.Seek(target)
}

