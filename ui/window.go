// appIcon is compiled into the binary so the same image shows up in the
// running window's title-bar / dock entry. The PNG variant is used here
// because Fyne's icon rendering goes through Go's image.Decode, which has
// no .ico support in stdlib — feeding it .ico bytes paints a black box.
// The .exe icon in File Explorer / Start menu comes from
// resource_windows_amd64.syso (generated by `rsrc -ico ui/go_music_icon_1.ico`).
//
//go:embed go_music_icon_1.png
var appIconBytes []byte
var appIconResource = fyne.NewStaticResource("gomusic.png", appIconBytes)

// Inline SVGs for transport buttons that don't have a clean equivalent in
