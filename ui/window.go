// installShortcuts wires keyboard control of playback. Single-key bindings
// (Space, Left, Right, S, L, R) go through Canvas.SetOnTypedKey; combinations
// with Ctrl go through Canvas.AddShortcut with a desktop.CustomShortcut.
//
// We also clear focus on every key press so that a focused button (e.g. the
// play button after a mouse click) does NOT also receive Space and toggle
// playback twice. The Fyne convention is that SetOnTypedKey fires whether or
// not anything is focused, but a focused Tappable will eat Space first — so
// we proactively unfocus on every shortcut fire and the keystroke routes
// only through our handler.
func (ui *mainUI) installShortcuts(w fyne.Window) {
	c := w.Canvas()

	unfocus := func() { c.Unfocus() }

	c.SetOnTypedKey(func(ev *fyne.KeyEvent) {
		// When the search entry has the keyboard, every printable / nav key
		// belongs to the editor, not to playback shortcuts. Esc closes the
		// bar (handled below); Enter just commits the current filter and
		// also closes. Everything else is forwarded to the entry by Fyne
		// automatically — we simply don't intercept it here.
		if c.Focused() == ui.searchEntry {
			switch ev.Name {
			case fyne.KeyEscape:
				ui.hideSearchBar()
			case fyne.KeyReturn, fyne.KeyEnter:
				unfocus()
			}
			return
		}

		switch ev.Name {
		case fyne.KeySpace:
			unfocus()
			ui.togglePlay()
		case fyne.KeyRight:
			ui.seekRelative(+5)
		case fyne.KeyLeft:
			ui.seekRelative(-5)
		case fyne.KeyUp:
			ui.adjustVolume(+0.05)
		case fyne.KeyDown:
			ui.adjustVolume(-0.05)
		case fyne.KeyS:
			ui.toggleShuffle()
		case fyne.KeyL:
			ui.toggleLyrics()
		case fyne.KeyR:
			ui.toggleRepeat()
		case fyne.KeyDelete:
			ui.removeCurrent()
		case fyne.KeyEscape:
			// Outside the search entry, Esc also clears any active filter.
			if ui.filtered != nil || (ui.searchBar != nil && ui.searchBar.Visible()) {
				ui.hideSearchBar()
			}
		}
	})

	// Modifier combos.
	addShortcut := func(key fyne.KeyName, mod fyne.KeyModifier, fn func()) {
		c.AddShortcut(&desktop.CustomShortcut{KeyName: key, Modifier: mod}, func(fyne.Shortcut) { fn() })
	}

	// Ctrl+←/→ jump tracks.
	addShortcut(fyne.KeyRight, fyne.KeyModifierControl, ui.goNext)
	addShortcut(fyne.KeyLeft, fyne.KeyModifierControl, ui.goPrev)
	// Ctrl+F focuses the playlist search bar.
	addShortcut(fyne.KeyF, fyne.KeyModifierControl, ui.showSearchBar)
	// Ctrl+Shift+↑/↓ reorder the playing track without interrupting playback.
	addShortcut(fyne.KeyUp, fyne.KeyModifierControl|fyne.KeyModifierShift, func() { ui.moveCurrent(-1) })
	addShortcut(fyne.KeyDown, fyne.KeyModifierControl|fyne.KeyModifierShift, func() { ui.moveCurrent(+1) })
}

func (ui *mainUI) adjustVolume(delta float64) {
	// We don't keep a slider reference, so volume is mutated directly on the
	// engine. The on-screen slider only updates next time the user opens its
	// row, but that's fine — keyboard volume adjustment is a power-user path.
	v := float64(ui.eng.Volume) + delta
	if v < 0 {
		v = 0
	}
	if v > 1 {
		v = 1
	}
	ui.eng.Volume = float32(v)
	ui.cfg.Volume = float32(v)
	ui.cfg.save()
}

// ── Crossfade ────────────────────────────────────────────────────────────────

// maybePreloadNext asks the engine to start decoding the next playlist
// track when the current one is close enough to its end that a crossfade
// could begin soon. Gated by:
//   - crossfade is enabled (>0)
//   - the current track is PCM (DSD doesn't crossfade)
//   - we're not in repeat-track mode (the engine would fade into a
//     different track than what we want to play next)
//   - there IS a next track to preload
//
// The threshold is crossfadeSec + 6 s so the decode has comfortably
// finished by the time the engine wants to fade. Called from
// OnPositionChange (4×/s), so the actual Preload call lands in the
// engine repeatedly — that's fine, Preload itself deduplicates by path
// and bails when something's already loaded / loading.
func (ui *mainUI) maybePreloadNext(pos, dur float64) {
	if ui.repeatTrack {
		return
	}
	cf := ui.eng.CrossfadeSeconds()
	if cf <= 0 {
		return
	}
	if ui.eng.Info != nil && ui.eng.Info.IsDSD {
		return
	}
	remaining := dur - pos
	if remaining > cf+6 {
		return
	}
	nxt := ui.pl.PeekNext()
	if nxt == nil {
		return
	}
	ui.eng.Preload(nxt.Path)
}

// toggleCrossfade flips crossfade between 0 (off) and 4 s (on). Persisted
// to config; the engine picks it up immediately (atomic store, no restart).
func (ui *mainUI) toggleCrossfade() {
	if ui.eng.CrossfadeSeconds() > 0 {
		ui.eng.SetCrossfade(0)
		ui.cfg.CrossfadeSec = 0
		ui.eng.ClearPreload()
	} else {
		ui.eng.SetCrossfade(4)
		ui.cfg.CrossfadeSec = 4
	}
	ui.cfg.save()
}

// toggleExclusiveMode flips WASAPI exclusive-vs-shared mode. The change
// only affects the NEXT Play() call — already-running playback finishes
// in whatever backend it opened with. The menu label reflects the new
// preference immediately so the user knows what they picked.
func (ui *mainUI) toggleExclusiveMode() {
	new := !ui.eng.ExclusiveMode()
	ui.eng.SetExclusiveMode(new)
	ui.cfg.ExclusiveMode = new
	ui.cfg.save()
}

// ── Search / filter ──────────────────────────────────────────────────────────

// rowToReal converts a visible-list row index into the canonical playlist
// index, honouring an active filter. -1 if out of range.
func (ui *mainUI) rowToReal(row int) int {
	if ui.filtered != nil {
		if row < 0 || row >= len(ui.filtered) {
			return -1
		}
		return ui.filtered[row]
	}
	if row < 0 || row >= ui.pl.Len() {
		return -1
	}
	return row
}

// realToRow is the inverse of rowToReal: turns a canonical playlist index
// into the corresponding visible-list row, or -1 if the track is currently
// hidden by an active filter.
func (ui *mainUI) realToRow(real int) int {
	if real < 0 {
		return -1
	}
	if ui.filtered == nil {
		if real >= ui.pl.Len() {
			return -1
		}
		return real
	}
	for row, r := range ui.filtered {
		if r == real {
			return row
		}
	}
	return -1
}

// syncListSelection refreshes the visible playlist AND updates Fyne's row
// hover/selection so it tracks the current playing song. Called from every
// path that changes pl.Current programmatically — auto-advance, prev/next,
// crossfade transition, album-from-library load. Without this the "▸"
// prefix and accent color move (via UpdateItem) but the system hover stays
// stuck on whatever row the user last clicked manually.
func (ui *mainUI) syncListSelection() {
	ui.listWidget.Refresh()
	row := ui.realToRow(ui.pl.Current)
	ui.suppressSelect = true
	defer func() { ui.suppressSelect = false }()
	if row < 0 {
		ui.listWidget.UnselectAll()
		return
	}
	ui.listWidget.Select(row)
	ui.listWidget.ScrollTo(row)
}

// applyFilter rebuilds `filtered` from the current query string. An empty
// query clears the filter (returns to showing every track).
func (ui *mainUI) applyFilter(q string) {
	q = strings.TrimSpace(strings.ToLower(q))
	if q == "" {
		ui.filtered = nil
	} else {
		ui.filtered = ui.filtered[:0]
		for i, t := range ui.pl.Tracks {
			if strings.Contains(strings.ToLower(t.Title), q) {
				ui.filtered = append(ui.filtered, i)
			}
		}
		if ui.filtered == nil {
			ui.filtered = []int{}
		}
	}
	ui.listWidget.Refresh()
}

// showSearchBar reveals the search row and focuses the entry. Called from
// Ctrl+F and the Edit menu.
func (ui *mainUI) showSearchBar() {
	if ui.searchBar == nil {
		return
	}
	ui.searchBar.Show()
	ui.win.Canvas().Focus(ui.searchEntry)
}

// hideSearchBar clears the query, drops the filter, and removes focus so
// the keyboard shortcuts route through SetOnTypedKey again.
func (ui *mainUI) hideSearchBar() {
	if ui.searchBar == nil {
		return
	}
	ui.searchEntry.SetText("")
	ui.applyFilter("")
	ui.searchBar.Hide()
	ui.win.Canvas().Unfocus()
}

// ── Playlist edit actions ────────────────────────────────────────────────────

// removeCurrent drops the playing track from the playlist and, if anything
// remains, jumps to the next one (which now sits at the old Current's index
// after the shift). With nothing left, playback fully stops.
func (ui *mainUI) removeCurrent() {
	if ui.pl.Current < 0 {
		return
	}
	wasPlaying := ui.eng.CurrentState() == audio.StatePlaying
	idx := ui.pl.Current
	ui.eng.Stop()
	ui.pl.Remove(idx)
	ui.applyFilter(ui.searchEntry.Text) // rebuild filter against new tracks
	ui.syncListSelection()
	if ui.pl.Len() == 0 {
		ui.stopPlayback()
		return
	}
	// Remove() already clamped Current; keep playing from there if we were
	// in the middle of a song so the deletion feels seamless.
	if wasPlaying {
		if t := ui.pl.CurrentTrack(); t != nil {
			ui.loadAndPlay(t.Path)
		}
	}
}

// moveCurrent shifts the playing track by `delta` rows (-1 = up, +1 = down).
// No-op at the boundaries. Doesn't interrupt playback.
func (ui *mainUI) moveCurrent(delta int) {
	if ui.pl.Current < 0 {
		return
	}
	to := ui.pl.Current + delta
	if to < 0 || to >= ui.pl.Len() {
		return
	}
	ui.pl.Move(ui.pl.Current, to)
	ui.applyFilter(ui.searchEntry.Text) // filtered indices may have shifted
	ui.syncListSelection()
}

// ── Actions ──────────────────────────────────────────────────────────────────

func (ui *mainUI) loadAndPlay(path string) {
	ui.lyricsToken++
	token := ui.lyricsToken

	// A user-initiated track change should drop any preload — otherwise
	// the engine might crossfade into a track the user no longer wants.
	ui.eng.ClearPreload()

	go func() {
		info, err := ui.eng.Load(path)
		if err != nil {
			fyne.Do(func() { dialog.ShowError(err, ui.win) })
			return
		}
		fyne.Do(func() {
			ui.applyMetadata(info)
			ui.updatingUI = true
			ui.progress.SetValue(0)
			ui.updatingUI = false
			ui.posLabel.Text = "0:00"
			ui.posLabel.Refresh()
			ui.wave.SetPosition(0)
			ui.durLabel.Text = fmtDuration(info.Duration)
			ui.durLabel.Refresh()
			ui.syncListSelection()
			ui.setEmptyLyrics("Searching for lyrics…")
		})
		if err := ui.eng.Play(); err != nil {
			fyne.Do(func() { dialog.ShowError(err, ui.win) })
		}

		// Fetch lyrics asynchronously — never block playback on a network call.
		go func(info *audio.FileInfo, tok int) {
			lines := audio.FetchLyrics(info)
			fyne.Do(func() {
				if tok != ui.lyricsToken {
					return // user moved on to another track; discard.
				}
				ui.setLyrics(lines)
			})
		}(info, token)
	}()
}

func (ui *mainUI) applyMetadata(info *audio.FileInfo) {
	// Title: prefer tag, fall back to filename.
	title := info.Title
	if title == "" {
		title = filepath.Base(info.Path)
	}
	ui.titleText.Text = title
	ui.titleText.Refresh()

	ui.artistText.Text = info.Artist
	ui.artistText.Refresh()

	album := info.Album
	if album == "" {
		album = "—"
	}
	ui.albumText.Text = album
	ui.albumText.Refresh()

	ui.formatText.Text = info.QualityLabel
	ui.formatText.Refresh()

	// Album art: real picture if available, otherwise a hash-tinted placeholder.
	// Either way, derive an accent color so the rest of the UI (gradient,
	// format label, waveform) can echo the current track's visual identity.
	if len(info.PictureData) > 0 {
		res := fyne.NewStaticResource("cover", info.PictureData)
		ui.artImage.Resource = res
		ui.artImage.Refresh()
		ui.artImage.Show()
		ui.artGlyph.Hide()
		// Reset accent immediately so the previous track's hue doesn't linger
		// for the ~30–50 ms the goroutine takes to decode and sample. The
		// brief flash to default green is less jarring than the previous
		// track's color still on screen with a new cover.
		ui.applyAccent(color.NRGBA{})
		// Decode + sample the cover off the UI goroutine: image.Decode of a
		// 500 KB JPEG takes long enough to be visible at load time. Token
		// guards against late results landing on a newer track.
		picBytes := info.PictureData
		tok := ui.lyricsToken // piggyback on the lyrics token — increments on every Load
		go func() {
			c, ok := dominantColor(picBytes)
			fyne.Do(func() {
				if tok != ui.lyricsToken {
					return // user moved on
				}
				if ok {
					ui.applyAccent(c)
				}
			})
		}()
	} else {
		ui.artImage.Hide()
		ui.artGlyph.Show()
		// Tint the placeholder rectangle by file hash so each track has a
		// distinct visual fingerprint, and reuse that same hue for the
		// ambient gradient so the player still feels track-aware even when
		// the file has no embedded art.
		sum := md5.Sum([]byte(info.Path))
		hashCol := color.NRGBA{
			R: 0x40 + (sum[0] >> 1),
			G: 0x40 + (sum[1] >> 1),
			B: 0x40 + (sum[2] >> 1),
			A: 0xff,
		}
		ui.artBg.FillColor = hashCol
		ui.artBg.Refresh()
		ui.applyAccent(hashCol)
	}
}

// applyAccent retints every UI element that follows the current track's
// dominant color: the ambient backdrop gradient, the quality / mode labels,
// and the waveform. Pass a zero-alpha color to restore the theme defaults
// (used during startup and after stop).
func (ui *mainUI) applyAccent(c color.NRGBA) {
	ui.currentAccent = c
	if c.A == 0 {
		// Reset to theme defaults.
		ui.bgGradient.StartColor = color.NRGBA{}
		ui.bgGradient.EndColor = color.NRGBA{}
		ui.bgGradient.Refresh()
		ui.formatText.Color = colorAccent
		ui.formatText.Refresh()
		ui.wave.SetAccent(color.NRGBA{})
		ui.refreshModeLabel(ui.eng)
		return
	}

	// Gradient: dominant color tinted way down at the top, fully transparent
	// at the bottom so the base bg shows through and the controls stay
	// readable. ~14% alpha is the sweet spot: visible hue without washing
	// the album art's contrast.
	ui.bgGradient.StartColor = tint(c, 0x24)
	ui.bgGradient.EndColor = color.NRGBA{}
	ui.bgGradient.Refresh()

	// Brightened version of the dominant color for text overlays — extracted
	// colors at native luminance often read as muddy on a near-black bg.
	bright := brighten(c, 0.45)
	ui.formatText.Color = bright
	ui.formatText.Refresh()

	ui.wave.SetAccent(c)

	// Mode label also follows the accent when exclusive mode is active.
	ui.refreshModeLabel(ui.eng)
}

func (ui *mainUI) togglePlay() {
	switch ui.eng.CurrentState() {
	case audio.StatePlaying:
		ui.eng.Pause()
	case audio.StatePaused:
		ui.eng.Play()
	case audio.StateStopped:
		if t := ui.pl.CurrentTrack(); t != nil {
			ui.loadAndPlay(t.Path)
		}
	}
}

// ── Menu ─────────────────────────────────────────────────────────────────────

func buildMenu(w fyne.Window, eng *audio.Engine, pl *playlist.Playlist, ui *mainUI) *fyne.MainMenu {
	openFile := fyne.NewMenuItem("Open File…", func() {
		fd := dialog.NewFileOpen(func(r fyne.URIReadCloser, err error) {
			if err != nil || r == nil {
				return
			}
			r.Close()
			path := r.URI().Path()
			if !playlist.IsSupported(path) {
				dialog.ShowError(fmt.Errorf("unsupported format: %s", filepath.Ext(path)), w)
				return
			}
			pl.Add(path)
			pl.SetCurrent(pl.Len() - 1)
			ui.applyFilter(ui.searchEntry.Text)
			ui.loadAndPlay(path)
		}, w)
		fd.SetFilter(storage.NewExtensionFileFilter([]string{".dsf", ".dff", ".flac", ".wav", ".mp3"}))
		fd.Show()
	})

	openFolder := fyne.NewMenuItem("Open Folder…", func() {
		dialog.ShowFolderOpen(func(lu fyne.ListableURI, err error) {
			if err != nil || lu == nil {
				return
			}
			pl.AddDir(lu.Path())
			ui.applyFilter(ui.searchEntry.Text)
			if t := pl.CurrentTrack(); t != nil {
				ui.loadAndPlay(t.Path)
			}
		}, w)
	})

	setMusicRoot := fyne.NewMenuItem("Set Music Root…", func() {
		dialog.ShowFolderOpen(func(lu fyne.ListableURI, err error) {
			if err != nil || lu == nil {
				return
			}
			ui.setMusicRoot(lu.Path())
		}, w)
	})

	rescanLibrary := fyne.NewMenuItem("Rescan Library", func() {
		if ui.cfg.MusicRoot == "" {
			dialog.ShowInformation("No music root",
				"Use \"Set Music Root…\" first to pick the folder to index.", w)
			return
		}
		ui.scanLibrary(ui.cfg.MusicRoot, true)
	})

	clearList := fyne.NewMenuItem("Clear Playlist", func() {
		eng.Stop()
		pl.Clear()
		ui.hideSearchBar() // drop any active filter so the empty list shows correctly
		ui.listWidget.Refresh()
		ui.titleText.Text = "No track loaded"
		ui.titleText.Refresh()
		ui.artistText.Text = ""
		ui.artistText.Refresh()
		ui.albumText.Text = "Open a file or folder to begin"
		ui.albumText.Refresh()
		ui.formatText.Text = ""
		ui.formatText.Refresh()
		ui.artImage.Hide()
		ui.artGlyph.Show()
		ui.artBg.FillColor = colorBgElevated
		ui.artBg.Refresh()
		ui.posLabel.Text = "0:00"
		ui.posLabel.Refresh()
		ui.durLabel.Text = "0:00"
		ui.durLabel.Refresh()
		ui.updatingUI = true
		ui.progress.SetValue(0)
		ui.updatingUI = false
	})

	// Edit menu — playlist manipulation. Shortcut hints are part of the
	// menu label since Fyne doesn't render OS-style accelerator badges.
	searchItem := fyne.NewMenuItem("Search…  (Ctrl+F)", ui.showSearchBar)
	moveUpItem := fyne.NewMenuItem("Move Up  (Ctrl+Shift+↑)", func() { ui.moveCurrent(-1) })
	moveDownItem := fyne.NewMenuItem("Move Down  (Ctrl+Shift+↓)", func() { ui.moveCurrent(+1) })
	removeItem := fyne.NewMenuItem("Remove Track  (Del)", ui.removeCurrent)

	// Crossfade toggle. The label shows the current state and flips on
	// click. Fyne doesn't auto-refresh menu labels, so after toggling we
	// rebuild the label and call w.MainMenu().Refresh().
	var crossfadeItem *fyne.MenuItem
	crossfadeLabel := func() string {
		if ui.eng.CrossfadeSeconds() > 0 {
			return fmt.Sprintf("Crossfade: %.0fs (click to disable)", ui.eng.CrossfadeSeconds())
		}
		return "Crossfade: off (click to enable 4s)"
	}
	crossfadeItem = fyne.NewMenuItem(crossfadeLabel(), func() {
		ui.toggleCrossfade()
		crossfadeItem.Label = crossfadeLabel()
		if mm := w.MainMenu(); mm != nil {
			mm.Refresh()
		}
	})

	// Exclusive-mode toggle. Same dynamic-label pattern as crossfade.
	// Hint to the user that it only kicks in on the next song since we
	// don't restart the active player just to swap backends.
	var exclusiveItem *fyne.MenuItem
	exclusiveLabel := func() string {
		if ui.eng.ExclusiveMode() {
			return "Exclusive mode: on (bit-perfect, mutes other apps)"
		}
		return "Exclusive mode: off (shared, other apps audible)"
	}
	exclusiveItem = fyne.NewMenuItem(exclusiveLabel(), func() {
		ui.toggleExclusiveMode()
		exclusiveItem.Label = exclusiveLabel()
		if mm := w.MainMenu(); mm != nil {
			mm.Refresh()
		}
	})

	return fyne.NewMainMenu(
		fyne.NewMenu("File",
			openFile, openFolder,
			fyne.NewMenuItemSeparator(),
			setMusicRoot, rescanLibrary,
			fyne.NewMenuItemSeparator(),
			clearList,
		),
		fyne.NewMenu("Edit",
			searchItem,
			fyne.NewMenuItemSeparator(),
			moveUpItem, moveDownItem, removeItem,
			fyne.NewMenuItemSeparator(),
			crossfadeItem, exclusiveItem,
		),
	)
}

