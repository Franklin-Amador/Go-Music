// ── Waveform animation loop ─────────────────────────────────────────────────

// runWaveformLoop pulls the latest audio envelope from the engine 30×/s and
// hands it to the waveform widget. Always running — the visualizer ring sits
// dormant when nothing's playing, so Waveform() just returns zeros (and the
// widget's smoothing eases the line back to flat).
func (ui *mainUI) runWaveformLoop() {
	const fps = 30
	const numPoints = 96
	const windowMs = 38 // a touch under 2 frames @ 30fps — feels responsive
	tick := time.NewTicker(time.Second / fps)
	defer tick.Stop()

	for range tick.C {
		if ui.wave == nil || ui.eng == nil || ui.eng.Vis == nil {
			continue
		}
		samples := ui.eng.Vis.Waveform(numPoints, windowMs)
		// Copy because the closure runs later on the UI thread.
		snap := make([]float32, len(samples))
		copy(snap, samples)
		fyne.Do(func() {
			ui.wave.SetValues(snap)
		})
	}
}

// ── Lyrics panel ─────────────────────────────────────────────────────────────

// toggleLyrics shows or hides the right-side lyrics panel by swapping the
// content of rightContainer. The window resizes the panel automatically.
func (ui *mainUI) toggleLyrics() {
	ui.showLyrics = !ui.showLyrics
	ui.rightContainer.RemoveAll()
	if ui.showLyrics {
		split := container.NewHSplit(ui.playerColumn, ui.lyricsPanel)
		split.Offset = 0.62
		ui.rightContainer.Add(split)
		// Snap the highlighted line into view if we already have lyrics.
		if len(ui.lyricsLines) > 0 && ui.eng.Info != nil {
			ui.updateLyricsPosition(ui.eng.Position())
		}
	} else {
		ui.rightContainer.Add(ui.playerColumn)
	}
	ui.rightContainer.Refresh()
}

// setEmptyLyrics replaces the panel contents with a single status line.
// Used while waiting for the network fetch or when no lyrics are found.
func (ui *mainUI) setEmptyLyrics(message string) {
	ui.lyricsLines = nil
	ui.currentLyric = -1
	ui.lyricsBox.RemoveAll()
	t := canvas.NewText(message, colorTextDim)
	t.TextSize = 13
	t.Alignment = fyne.TextAlignCenter
	ui.lyricsBox.Add(t)
	ui.lyricsBox.Refresh()
}

// setEmptyLyricsWithRetry shows the empty-state message plus a "Retry" button
// that re-runs the lyrics lookup for the currently-loaded track. Used when
// the first fetch came back empty (no LRC, no embedded tag, nothing on
// LRCLIB) so the user can re-attempt after they're back online or after
// LRCLIB has been updated. The cached negative result is invalidated before
// the new lookup so the same empty answer can't short-circuit the retry.
func (ui *mainUI) setEmptyLyricsWithRetry(message string) {
	ui.lyricsLines = nil
	ui.currentLyric = -1
	ui.lyricsBox.RemoveAll()

	t := canvas.NewText(message, colorTextDim)
	t.TextSize = 13
	t.Alignment = fyne.TextAlignCenter

	retryBtn := widget.NewButtonWithIcon("Retry lookup", theme.ViewRefreshIcon(), func() {
		info := ui.eng.Info
		if info == nil {
			return
		}
		// Drop the cached empty result and re-query. Use the same search
		// title that FetchLyrics derives (track-number prefix stripped from
		// the tag title, falling back to the filename base).
		artist := info.Artist
		title := info.Title
		if title == "" {
			title = strings.TrimSuffix(filepath.Base(info.Path), filepath.Ext(info.Path))
		}
		audio.ClearLyricsCacheFor(artist, title)

		ui.lyricsToken++
		tok := ui.lyricsToken
		ui.setEmptyLyrics("Searching for lyrics…")
		go func(info *audio.FileInfo, tok int) {
			lines := audio.FetchLyrics(info)
			fyne.Do(func() {
				if tok != ui.lyricsToken {
					return
				}
				ui.setLyrics(lines)
			})
		}(info, tok)
	})
	retryBtn.Importance = widget.LowImportance

	ui.lyricsBox.Add(t)
	ui.lyricsBox.Add(container.NewCenter(retryBtn))
	ui.lyricsBox.Refresh()
}

// setLyrics replaces the panel contents with the given lines, prepared for
// position-driven highlighting (synced) or static display (plain).
func (ui *mainUI) setLyrics(lines []audio.LyricLine) {
	if len(lines) == 0 {
		ui.setEmptyLyricsWithRetry("No lyrics found")
		return
	}
	ui.lyricsLines = lines
	ui.currentLyric = -1
	ui.lyricsBox.RemoveAll()
	for _, ln := range lines {
		t := canvas.NewText(ln.Text, colorTextDim)
		t.TextSize = 14
		t.Alignment = fyne.TextAlignCenter
		ui.lyricsBox.Add(t)
	}
	ui.lyricsBox.Refresh()
	ui.lyricsScroll.ScrollToTop()
}

// Lyric styling constants — keep activation/deactivation visually consistent.
//
// Sizes are calibrated for an "Apple Music desktop" feel: active line is
// dramatically larger than the surrounding idle lines so it commands focus
// even when the panel is glanced at from across the room. Adjacent lines
// take a middle size (lyricSizeNear) so the transition between idle and
// active doesn't feel like a hard step.
const (
	lyricSizeIdle      float32 = 14
	lyricSizeNear      float32 = 16
	lyricSizeActive    float32 = 22
	lyricAnimDur               = 200 * time.Millisecond
	lyricScrollDur             = 420 * time.Millisecond
	lyricLineHeightHint        = float32(32)
)

// updateLyricsPosition highlights the line whose timestamp matches the current
// playback position and scrolls it into view. No-op for plain (unsynced)
// lyrics — those just sit there.
//
// Visual treatment (depth-of-field, Apple-Music-inspired):
//   - The new active line fades to the album's accent color, bolds, and grows
//     to lyricSizeActive (22 px).
//   - Lines immediately above/below (±1) take an intermediate size and full
//     white color, so the transition into the active band is smooth.
//   - Everything else relaxes back to colorTextDim @ lyricSizeIdle.
//   - The scroll glides to center the active line in the viewport.
//
// Any animations still in flight from the previous line change are stopped
// before new ones start, so rapid line changes can't pile up.
func (ui *mainUI) updateLyricsPosition(posSec float64) {
	if len(ui.lyricsLines) == 0 {
		return
	}
	if !ui.lyricsLines[0].IsSynced() {
		return
	}
	target := time.Duration(posSec * float64(time.Second))
	idx := -1
	for i, ln := range ui.lyricsLines {
		if ln.Time <= target {
			idx = i
		} else {
			break
		}
	}
	if idx == ui.currentLyric {
		return
	}
	prev := ui.currentLyric
	ui.currentLyric = idx

	ui.stopLyricAnims()

	// Build the set of lines whose visual state changes this cycle: the new
	// active, its ±1 neighbors, plus the previously-active and ITS neighbors
	// so they relax back to idle as the focus moves. Using a set avoids
	// double-animating the same line when prev and idx are adjacent.
	touched := map[int]struct{}{}
	for _, i := range []int{prev - 1, prev, prev + 1, idx - 1, idx, idx + 1} {
		if i >= 0 && i < len(ui.lyricsBox.Objects) {
			touched[i] = struct{}{}
		}
	}

	// Accent for the active line follows the album's dominant color when
	// available, falling back to the static green so first-frame loads still
	// have a highlight.
	activeCol := color.Color(colorAccent)
	if ui.currentAccent.A != 0 {
		activeCol = brighten(ui.currentAccent, 0.45)
	}

	for i := range touched {
		t, ok := ui.lyricsBox.Objects[i].(*canvas.Text)
		if !ok {
			continue
		}
		switch i {
		case idx:
			t.TextStyle = fyne.TextStyle{Bold: true}
			ui.animateLineTo(t, activeCol, lyricSizeActive)
		case idx - 1, idx + 1:
			t.TextStyle = fyne.TextStyle{}
			ui.animateLineTo(t, colorText, lyricSizeNear)
		default:
			t.TextStyle = fyne.TextStyle{}
			ui.animateLineTo(t, colorTextDim, lyricSizeIdle)
		}
	}

	if idx >= 0 {
		viewportH := ui.lyricsScroll.Size().Height
		desiredY := float32(idx)*lyricLineHeightHint - viewportH/2 + lyricLineHeightHint
		if desiredY < 0 {
			desiredY = 0
		}
		ui.animateScrollTo(desiredY)
	}
}

// stopLyricAnims halts every in-flight color/size animation on the lyric
// lines plus the scroll animation. Leaves the canvas in whatever intermediate
// state it was in — the next animateLineTo / animateScrollTo will start from
// there, so transitions stay visually continuous.
func (ui *mainUI) stopLyricAnims() {
	for _, a := range ui.lineAnims {
		if a != nil {
			a.Stop()
		}
	}
	ui.lineAnims = ui.lineAnims[:0]
	if ui.scrollAnim != nil {
		ui.scrollAnim.Stop()
		ui.scrollAnim = nil
	}
}

// animateLineTo runs a paired color + size animation on a single lyric line.
// Both start from the line's current rendered state so a stopped-mid-flight
// previous animation continues smoothly from where it was.
func (ui *mainUI) animateLineTo(t *canvas.Text, toCol color.Color, toSize float32) {
	fromCol := t.Color
	if fromCol == nil {
		fromCol = colorTextDim
	}
	fromSize := t.TextSize
	if fromSize <= 0 {
		fromSize = lyricSizeIdle
	}

	colorAnim := canvas.NewColorRGBAAnimation(fromCol, toCol, lyricAnimDur, func(c color.Color) {
		t.Color = c
		t.Refresh()
	})
	colorAnim.Curve = fyne.AnimationEaseOut
	colorAnim.Start()

	sizeAnim := fyne.NewAnimation(lyricAnimDur, func(f float32) {
		t.TextSize = fromSize + (toSize-fromSize)*f
		t.Refresh()
	})
	sizeAnim.Curve = fyne.AnimationEaseOut
	sizeAnim.Start()

	ui.lineAnims = append(ui.lineAnims, colorAnim, sizeAnim)
}

// animateScrollTo glides the lyrics viewport offset to y over lyricScrollDur.
// Uses ease-in-out so the motion feels deliberate rather than abrupt.
func (ui *mainUI) animateScrollTo(y float32) {
	if ui.lyricsScroll == nil {
		return
	}
	start := ui.lyricsScroll.Offset.Y
	if start == y {
		return
	}
	anim := fyne.NewAnimation(lyricScrollDur, func(f float32) {
		ui.lyricsScroll.Offset = fyne.NewPos(0, start+(y-start)*f)
		ui.lyricsScroll.Refresh()
	})
	anim.Curve = fyne.AnimationEaseInOut
	anim.Start()
	ui.scrollAnim = anim
}

// refreshModeLabel updates the audio output mode indicator in the time row.
// Exclusive follows the current track's accent (brightened for legibility on
// a dark background); shared stays dim gray. Updates every ticker tick and
// every track load so the color stays in sync with the album art.
func (ui *mainUI) refreshModeLabel(eng *audio.Engine) {
	mode := eng.OutputMode()
	var text string
	var col color.Color
	switch mode {
	case "exclusive":
		text = "EXCLUSIVE"
		if ui.currentAccent.A != 0 {
			col = brighten(ui.currentAccent, 0.45)
		} else {
			col = colorAccent
		}
	case "shared":
		text = "SHARED"
		col = colorTextDim
	default:
		text = ""
		col = colorTextDim
	}
	ui.modeLabel.Text = text
	ui.modeLabel.Color = col
	ui.modeLabel.Refresh()
}
