// Run starts the Fyne application event loop. Blocks until the window closes.
func Run() {
	a := app.NewWithID("com.gomusic.player")
	a.Settings().SetTheme(gomusicTheme{})
	a.SetIcon(appIconResource)

	w := a.NewWindow("Go Music")
	w.SetIcon(appIconResource)
	// Open at a comfortable size that fits a 1366×768 laptop with taskbar
	// (working area ≈ 728 px tall). Going taller — even though it looks
	// nice on a desktop — gets clamped by the OS on small screens and then
	// the user can't shrink the window because the content's MinSize is
	// already close to that clamped maximum. Users on big monitors can
	// drag-resize or maximize from this baseline.
	w.Resize(fyne.NewSize(1080, 720))
	w.CenterOnScreen()

	cfg := loadConfig()

	eng := audio.NewEngine()
	eng.Volume = cfg.Volume
	eng.SetCrossfade(cfg.CrossfadeSec)
	eng.SetExclusiveMode(cfg.ExclusiveMode)

	pl := playlist.New()
	for _, path := range cfg.PlaylistPaths {
		pl.Add(path)
	}
	if cfg.CurrentIndex >= 0 && cfg.CurrentIndex < pl.Len() {
		pl.SetCurrent(cfg.CurrentIndex)
	}

	ui := buildUI(w, eng, pl, cfg)
	// Load the cached library index (if any) BEFORE the first
	// refreshLibraryUI pass so the Albums / Artists tabs already have
	// content when the window paints. Missing/corrupt cache silently
	// leaves ui.lib nil and the placeholder text shows.
	ui.loadCachedLibrary()
	ui.refreshLibraryUI()
	w.SetContent(ui.root)
	w.SetMainMenu(buildMenu(w, eng, pl, ui))
	ui.installShortcuts(w)

	// Register the OS-level multimedia keys (Play/Pause/Next/Prev) so they
	// work even when the app doesn't have focus. Callbacks fire on a
	// dedicated message-pump thread; we route them through fyne.Do so the
	// UI handlers always run on the Fyne goroutine like every other
	// shortcut path.
	startMediaKeys(mediaKeysHandler{
		OnPlayPause: func() { fyne.Do(ui.togglePlay) },
		OnNext:      func() { fyne.Do(ui.goNext) },
		OnPrev:      func() { fyne.Do(ui.goPrev) },
		OnStop:      func() { fyne.Do(ui.stopPlayback) },
	})

	go ui.runWaveformLoop()

	w.SetOnClosed(func() {
		cfg.Volume = eng.Volume
		cfg.ShowLyrics = ui.showLyrics
		cfg.CurrentIndex = pl.Current
		cfg.CrossfadeSec = eng.CrossfadeSeconds()
		cfg.ExclusiveMode = eng.ExclusiveMode()
		paths := make([]string, len(pl.Tracks))
		for i, t := range pl.Tracks {
			paths[i] = t.Path
		}
		cfg.PlaylistPaths = paths
		cfg.save()
	})

	w.ShowAndRun()
}

